// TV Display is intentionally not a nav item — it's a standalone kiosk
// view (reached by its own URL on the TV's browser), not part of the
// phone/desktop web app navigation.
export const NAV_ITEMS = (role: SessionUser["role"]) => [
  { href: "/dashboard", label: "Dashboard", icon: DashboardIcon },
  ...(role === "manager" ? [{ href: "/admin", label: "Admin", icon: AdminIcon }] : []),
  { href: "/settings", label: "Settings", icon: SettingsIcon },
];

/** Desktop icon-only vertical sidebar. Hidden below the sm breakpoint, where BottomNav takes over. */
export function Sidebar({ user }: { user: SessionUser }) {
  const pathname = usePathname();
  const router = useRouter();
  const items = NAV_ITEMS(user.role);

  async function logout() {
    await fetch("/api/auth/logout", { method: "POST" });
    router.push("/login");
    router.refresh();
  }

  return (
    <nav
      aria-label="Primary"
      className="sidebar hidden sm:flex flex-col items-center justify-between py-6 px-3 w-20 shrink-0"
    >
      <div className="flex flex-col items-center gap-6">
        {items.map((item) => {
          const active = pathname.startsWith(item.href);
          const Icon = item.icon;
          return (
            <Link
              key={item.href}
              href={item.href}
              title={item.label}
              aria-label={item.label}
              aria-current={active ? "page" : undefined}
              className={clsx("sidebar-icon", active && "sidebar-icon-active")}
            >
              <Icon />
            </Link>
          );
        })}
      </div>
      <button onClick={logout} title="Log out" aria-label="Log out" className="sidebar-icon">
        <LogoutIcon />
      </button>
    </nav>
  );
}
